"""Minimal Source RCON client and server.properties helpers.

Minecraft servers expose a small TCP protocol called Source RCON. Slime uses it
to control a server that was started by another process (the TUI, a foreground
``slime server run``, or even a plain ``java -jar``). The protocol is
intentionally tiny: every packet is a little-endian length, a request id, a
type, a UTF-8 payload and two NUL bytes.

RCON is only enabled for non-proxy servers. Slime adds ``enable-rcon``,
``rcon.port`` and a random ``rcon.password`` to ``server.properties`` for new
servers, and fills them in for existing servers unless the user explicitly set
``enable-rcon=false``. Minecraft applies the change on the next start.
"""

from __future__ import annotations

import contextlib
import secrets
import select
import socket
import struct
import time
from dataclasses import dataclass
from pathlib import Path

from .errors import RconError
from .models import Project
from .properties import read_properties, write_properties

DEFAULT_RCON_PORT = 25575
#: Offset used when deriving a per-server RCON port from the game port.
RCON_PORT_OFFSET = 10
_MAX_PACKET_SIZE = 8 * 1024 * 1024
_RESPONSE_GRACE = 0.25
_PROPERTIES_HEADER = "#Minecraft server properties\n#Generated by Slime"

_TYPE_RESPONSE = 0
_TYPE_COMMAND = 2
_TYPE_AUTH_RESPONSE = 2
_TYPE_AUTH = 3


@dataclass(frozen=True, slots=True)
class RconConfig:
    """Connection settings read from ``server.properties``."""

    host: str
    port: int
    password: str

    @property
    def address(self) -> str:
        return f"{self.host}:{self.port}"


def _default_port(server_port: int) -> int:
    candidate = server_port + RCON_PORT_OFFSET
    if candidate == server_port or not 1 <= candidate <= 65535:
        return DEFAULT_RCON_PORT
    return candidate


def _parse_port(value: str) -> int | None:
    try:
        port = int(value.strip())
    except (TypeError, ValueError):
        return None
    return port if 1 <= port <= 65535 else None


def read_rcon_config(server_dir: Path) -> RconConfig | None:
    """Return RCON settings, or ``None`` when RCON is disabled/misconfigured."""
    properties = read_properties(Path(server_dir) / "server.properties")
    if properties.get("enable-rcon", "").strip().lower() != "true":
        return None
    port = _parse_port(properties.get("rcon.port", ""))
    password = properties.get("rcon.password", "")
    if port is None or not password:
        return None
    return RconConfig("127.0.0.1", port, password)


def ensure_rcon_config(server_dir: Path, server_port: int) -> RconConfig | None:
    """Enable RCON in ``server.properties`` and return the resulting settings.

    An explicit ``enable-rcon=false`` is respected so users can opt out. A
    missing password or port is filled in; existing values are preserved.
    """
    path = Path(server_dir) / "server.properties"
    properties = read_properties(path)
    enabled = properties.get("enable-rcon", "").strip().lower()
    if enabled == "false":
        return None

    changed = False
    if enabled != "true":
        properties["enable-rcon"] = "true"
        changed = True

    password = properties.get("rcon.password", "").strip()
    if not password:
        password = secrets.token_urlsafe(24)
        properties["rcon.password"] = password
        changed = True

    port = _parse_port(properties.get("rcon.port", ""))
    if port is None or port == server_port:
        port = _default_port(server_port)
        properties["rcon.port"] = str(port)
        changed = True

    if changed:
        write_properties(
            path,
            properties,
            header=_PROPERTIES_HEADER,
            merge=False,
        )
    return RconConfig("127.0.0.1", port, password)


def require_rcon_config(server_dir: Path) -> RconConfig:
    """Return RCON settings or raise a helpful :class:`RconError`."""
    config = read_rcon_config(server_dir)
    if config is None:
        raise RconError(
            "RCON is not enabled for this server.",
            hint=(
                "Start the server once with Slime (it adds enable-rcon, "
                "rcon.port and rcon.password automatically), or set them in "
                "server.properties and restart the server."
            ),
        )
    return config


def shutdown_command(server: object) -> str:
    """Return the console command that stops a server or proxy."""
    project = getattr(server, "project", None)
    if project is Project.VELOCITY:
        return "shutdown"
    if project is Project.WATERFALL:
        return "end"
    return "stop"


class RconClient:
    """A small synchronous Source RCON client.

    Use it as a context manager::

        with RconClient(config) as client:
            print(client.command("list"))
    """

    def __init__(
        self,
        config: RconConfig,
        *,
        timeout: float = 5.0,
    ) -> None:
        self.config = config
        self.timeout = timeout
        self._socket: socket.socket | None = None
        self._request_id = 0

    def __enter__(self) -> RconClient:
        self.connect()
        return self

    def __exit__(self, *_: object) -> None:
        self.close()

    # ------------------------------------------------------------------ socket
    def connect(self) -> None:
        if self._socket is not None:
            return
        try:
            sock = socket.create_connection(
                (self.config.host, self.config.port), timeout=self.timeout
            )
        except OSError as exc:
            raise RconError(
                f"Could not connect to RCON at {self.config.address}: {exc}",
                hint="Check that the server is running and RCON is enabled.",
            ) from exc
        sock.settimeout(self.timeout)
        self._socket = sock
        try:
            self._authenticate()
        except Exception:
            self.close()
            raise

    def close(self) -> None:
        if self._socket is not None:
            with contextlib.suppress(OSError):
                self._socket.close()
            self._socket = None

    def command(self, command: str) -> str:
        """Send one console command and return the full response."""
        command = command.strip()
        if not command:
            return ""
        self.connect()
        request_id = self._next_request_id()
        try:
            self._send(request_id, _TYPE_COMMAND, command.encode("utf-8"))
            return self._read_response(request_id)
        except OSError as exc:
            self.close()
            raise RconError(f"RCON connection lost: {exc}") from exc

    # ----------------------------------------------------------------- packets
    def _authenticate(self) -> None:
        request_id = self._next_request_id()
        try:
            self._send(request_id, _TYPE_AUTH, self.config.password.encode("utf-8"))
            response_id, packet_type, _payload = self._read_packet()
        except OSError as exc:
            raise RconError(
                f"RCON authentication to {self.config.address} failed: {exc}",
                hint="Check rcon.password in server.properties.",
            ) from exc
        if response_id == -1 or packet_type != _TYPE_AUTH_RESPONSE:
            raise RconError(
                "RCON authentication failed.",
                hint="The password in server.properties does not match.",
            )

    def _next_request_id(self) -> int:
        self._request_id = (self._request_id + 1) % 2_147_483_647
        if self._request_id == 0:
            self._request_id = 1
        return self._request_id

    def _send(self, request_id: int, packet_type: int, payload: bytes) -> None:
        assert self._socket is not None
        body = struct.pack("<ii", request_id, packet_type) + payload + b"\x00\x00"
        self._socket.sendall(struct.pack("<i", len(body)) + body)

    def _recv_exact(self, size: int) -> bytes:
        assert self._socket is not None
        chunks: list[bytes] = []
        remaining = size
        while remaining:
            chunk = self._socket.recv(remaining)
            if not chunk:
                raise OSError("RCON connection closed by the server.")
            chunks.append(chunk)
            remaining -= len(chunk)
        return b"".join(chunks)

    def _read_packet(self) -> tuple[int, int, bytes]:
        raw_length = self._recv_exact(4)
        (length,) = struct.unpack("<i", raw_length)
        if length < 10 or length > _MAX_PACKET_SIZE:
            raise RconError(
                f"Invalid RCON packet length: {length}.",
                hint="The port may belong to a different service.",
            )
        data = self._recv_exact(length)
        request_id, packet_type = struct.unpack("<ii", data[:8])
        payload = data[8:-2]
        return request_id, packet_type, payload

    def _read_response(self, request_id: int) -> str:
        chunks: list[str] = []
        deadline = time.monotonic() + self.timeout
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                if chunks:
                    break
                raise RconError("Timed out waiting for an RCON response.")
            assert self._socket is not None
            wait = min(remaining, _RESPONSE_GRACE) if chunks else remaining
            try:
                readable, _, _ = select.select([self._socket], [], [], wait)
            except OSError as exc:
                raise RconError(f"RCON connection lost: {exc}") from exc
            if not readable:
                if chunks:
                    break
                raise RconError("Timed out waiting for an RCON response.")
            packet_id, packet_type, payload = self._read_packet()
            if packet_id == -1:
                raise RconError("RCON authentication failed.")
            if packet_id != request_id or packet_type != _TYPE_RESPONSE:
                continue
            if not payload:
                break
            chunks.append(payload.decode("utf-8", errors="replace"))
        return "".join(chunks)


